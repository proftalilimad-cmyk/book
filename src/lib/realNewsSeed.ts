/** يبني مقالات المحتوى الافتتاحي الحقيقي (منشورة، غير تجريبية) */
export function buildRealNewsArticles(): Article[] {
  const now = Date.now();
  return ITEMS.map((it, i) => {
    const published = new Date(now - it.hoursAgo * 3600_000).toISOString();
    const id = `real-seed-${String(i + 1).padStart(2, '0')}`;
    const content = it.paragraphs.map((p) => `<p>${p}</p>`).join('\n');
    return {
      id,
      title: it.title,
      subtitle: it.subtitle,
      slug: `${slugifyAr(it.title)}-${id}`,
      summary: it.summary,
      content,
      category: it.category,
      region: it.region,
      tags: it.tags,
      featured_image: it.image,
      source_name: it.source_name,
      source_url: it.source_url,
      source_published_at: it.source_published_at,
      author_name: 'تحرير NEWS MAROC',
      status: 'published',
      is_breaking: it.breaking === true,
      is_demo: false,
      views: 120 + Math.floor(seededRandom(id) * 2800),
      published_at: published,
      created_at: published,
      updated_at: published,
      meta_title: it.title.length > 68 ? `${it.title.slice(0, 65)}…` : it.title,
      meta_description: it.summary.length > 158 ? `${it.summary.slice(0, 155)}…` : it.summary,
      keywords: it.keywords,
      agent_log: [
        {
          at: published,
          step: 'EDITORIAL',
          note: `خبر حقيقي موثّق من «${it.source_name}» — صياغة تحريرية مستقلة عن نص المصدر مع الاحتفاظ بالوقائع والإسناد الكامل (محتوى افتتاحي بطلب مالك الموقع).`,
        },
        { at: published, step: 'PUBLISHED', note: 'نُشر بقرار تحريري من مالك المنصة.' },
      ],
    } satisfies Article;
  });
}
